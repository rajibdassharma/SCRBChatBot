"""
ocr_index_smac.py — Index scanned SMAC PDFs using Docling with OCR enabled.

Reads pdfs_pending_ocr.txt (generated by bulk_index_smac.py) and processes
each scanned PDF with OCR-enabled Docling for table extraction.

This is a standalone script that directly imports backend modules — it does
NOT go through the FastAPI backend. This avoids HTTP overhead and allows
the OCR-enabled Docling converter to be used separately from the main
(non-OCR) converter.

Usage:
    cd backend/
    python ../dbscripts/ocr_index_smac.py

    # Custom OCR pending file:
    python ../dbscripts/ocr_index_smac.py --pending-file /path/to/pdfs_pending_ocr.txt

    # Dry run (show files, don't process):
    python ../dbscripts/ocr_index_smac.py --dry-run

    # Limit to N files (for testing):
    python ../dbscripts/ocr_index_smac.py --limit 5

    # Specify collection and case-id:
    python ../dbscripts/ocr_index_smac.py --collection SMAC --case-id 0
"""

